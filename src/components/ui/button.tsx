import * as React from 'react';
import { Button as BaseButton } from '@base-ui/react';
import { cva, type VariantProps } from 'class-variance-authority';
import { cn } from '@/lib/utils';

const buttonVariants = cva(
  'inline-flex items-center justify-center gap-2 whitespace-nowrap rounded-md text-sm font-medium transition-colors focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-prussian-blue focus-visible:ring-offset-2 disabled:pointer-events-none disabled:opacity-50 [&_svg]:pointer-events-none [&_svg]:size-4 [&_svg]:shrink-0 cursor-pointer',
  {
    variants: {
      variant: {
        default:
          'bg-prussian-blue text-ink-inverse shadow-sm hover:bg-prussian-blue-strong',
        destructive:
          'bg-vermilion text-ink-inverse shadow-sm hover:bg-vermilion-strong',
        outline:
          'border border-sheet-border bg-surface-raised hover:bg-surface-hover text-ink-primary',
        secondary:
          'bg-prussian-blue-subtle text-prussian-blue-strong border border-prussian-blue-border hover:bg-prussian-blue-subtle-hover',
        ghost: 'hover:bg-surface-hover text-ink-primary',
        link: 'text-prussian-blue underline-offset-4 hover:underline',
      },
      size: {
        default: 'h-9 px-4 py-2',
        sm: 'h-8 rounded-md px-3 text-xs',
        lg: 'h-10 rounded-md px-8 text-base',
        icon: 'h-9 w-9',
      },
    },
    defaultVariants: {
      variant: 'default',
      size: 'default',
    },
  }
);

export interface ButtonProps
  extends React.ComponentProps<typeof BaseButton>,
    VariantProps<typeof buttonVariants> {}

const Button = React.forwardRef<HTMLButtonElement, ButtonProps>(
  ({ className, variant, size, ...props }, ref) => {
    return (
      <BaseButton
        ref={ref}
        className={cn(buttonVariants({ variant, size, className }))}
        {...props}
      />
    );
  }
);
Button.displayName = 'Button';

export { Button, buttonVariants };
